VOICE = "zh-TW-HsiaoChenNeural"
OUTPUT_DIR = r"d:\Mume\20260609-50starup\video_project\app\assets_v2"

os.makedirs(OUTPUT_DIR, exist_ok=True)

for scene_id, text in SCENES.items():
    print(f"Generating audio for {scene_id}...")
    mp3_path = os.path.join(OUTPUT_DIR, f"{scene_id}.mp3")
    vtt_path = os.path.join(OUTPUT_DIR, f"{scene_id}.vtt")
    
    # Run edge-tts cli
    cmd = [
        "edge-tts",
        "--voice", VOICE,
        "--text", text,
        "--write-media", mp3_path,
        "--write-subtitles", vtt_path
    ]
    subprocess.run(cmd, check=True)
    print(f"Saved {mp3_path} and {vtt_path}")

print("All TTS and Subtitles generated successfully!")
